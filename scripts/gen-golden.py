"""Independent oracle for the RICE/WSJF golden tests.

Plain Python with no code shared with the TypeScript implementation. Run from the repo root:
    python3 scripts/gen-golden.py
It rewrites packages/core/src/scoring/__fixtures__/golden.json.
"""
import json
import random

random.seed(42)
IMPACT = [0.25, 0.5, 1, 2, 3]
FIB = [1, 2, 3, 5, 8, 13, 20]

rice = [
    {"id": "zero-reach", "reach": 0, "impact": 1, "confidence": 1, "effort": 1},
    {"id": "zero-conf", "reach": 100, "impact": 3, "confidence": 0, "effort": 2},
    {"id": "tie-a", "reach": 100, "impact": 1, "confidence": 1, "effort": 2},
    {"id": "tie-b", "reach": 50, "impact": 1, "confidence": 1, "effort": 1},  # same score as tie-a, lower effort wins
    {"id": "tie-c", "reach": 50, "impact": 1, "confidence": 1, "effort": 1},  # identical to tie-b, id breaks the tie
    {"id": "tiny-effort", "reach": 10, "impact": 0.25, "confidence": 0.5, "effort": 0.1},
]
while len(rice) < 24:
    rice.append({
        "id": f"r{len(rice):02d}",
        "reach": random.choice([0, 10, 250, 1000, 4800, 10000]),
        "impact": random.choice(IMPACT),
        "confidence": random.choice([0.1, 0.3, 0.5, 0.8, 1]),
        "effort": random.choice([0.5, 1, 2, 3.5, 8, 13]),
    })
for r in rice:
    r["title"] = r["id"]
    r["score"] = r["reach"] * r["impact"] * r["confidence"] / r["effort"]
rice_order = [r["id"] for r in sorted(rice, key=lambda r: (-r["score"], r["effort"], r["id"]))]

wsjf = [
    {"id": "w-tie-1", "businessValue": 5, "timeCriticality": 3, "riskReductionOpportunity": 2, "jobSize": 5},
    {"id": "w-tie-2", "businessValue": 3, "timeCriticality": 2, "riskReductionOpportunity": 1, "jobSize": 3},
    {"id": "w-max", "businessValue": 20, "timeCriticality": 20, "riskReductionOpportunity": 20, "jobSize": 1},
    {"id": "w-min", "businessValue": 1, "timeCriticality": 1, "riskReductionOpportunity": 1, "jobSize": 20},
]
while len(wsjf) < 22:
    wsjf.append({"id": f"w{len(wsjf):02d}", **{k: random.choice(FIB) for k in
                 ["businessValue", "timeCriticality", "riskReductionOpportunity", "jobSize"]}})
for w in wsjf:
    w["title"] = w["id"]
    w["score"] = (w["businessValue"] + w["timeCriticality"] + w["riskReductionOpportunity"]) / w["jobSize"]
wsjf_order = [w["id"] for w in sorted(wsjf, key=lambda w: (-w["score"], w["jobSize"], w["id"]))]

with open("packages/core/src/scoring/__fixtures__/golden.json", "w") as f:
    json.dump({
        "_comment": "Generated by scripts/gen-golden.py (independent Python oracle). Do not edit by hand.",
        "rice": {"items": rice, "expectedOrder": rice_order},
        "wsjf": {"items": wsjf, "expectedOrder": wsjf_order},
    }, f, indent=1)
    f.write("\n")
